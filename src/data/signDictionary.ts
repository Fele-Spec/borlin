type FingerJoints = [number, number, number][];

const makeFinger = (
  baseX: number,
  baseY: number,
  length: number,
  spread: number = 0,
  curl: number = 0
): FingerJoints => {
  const joints: FingerJoints = [];
  for (let i = 0; i < 4; i++) {
    const t = (i + 1) / 4;
    const curlOffset = curl * t * t * 0.15;
    joints.push([
      baseX + spread * t,
      baseY - length * t + curlOffset,
      curl * t * 0.08,
    ]);
  }
  return joints;
};

